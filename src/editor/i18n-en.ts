// Translate only complete known phrases separated by UI punctuation. Do not replace
// substrings inside an unknown user label or run translated output through the map again.
const phrasePattern = /([^\n\r·；;]+)([\n\r·；;]|$)/gu;

export function translateEnglish(text: string): string {
  const value = text.trim();
  if (!value || !/[\u3400-\u9fff]/u.test(value)) return text;
  let translated = englishMessages[value];
  if (translated === undefined) {
    for (const [pattern, render] of dynamicMessages) {
      const match = pattern.exec(value);
      if (match) { translated = render(...match.slice(1)); break; }
    }
  }
  if (translated === undefined) {
    translated = value.replace(phrasePattern, (_match, phrase: string, separator: string) => {
      const trimmed = phrase.trim(), replacement = englishMessages[trimmed];
      return replacement === undefined ? phrase + separator : phrase.replace(trimmed, replacement) + separator;
    });
  }
  return text.slice(0, text.indexOf(value)) + translated + text.slice(text.indexOf(value) + value.length);
}
